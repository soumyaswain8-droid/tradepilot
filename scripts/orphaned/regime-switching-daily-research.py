#!/usr/bin/env python3
"""
Daily regime-switching research watchdog.

Fires every morning at 07:00 IST via LaunchAgent. Each run:
  1. Picks today's topic from the rotation (deterministic by date)
  2. Writes a starter file at docs/research/regime-switching-daily/YYYY-MM-DD.md
     pre-populated with the topic, prior-cycle reference (if any), and the
     research-agent prompt to paste into Claude
  3. Sends a Telegram with the topic and starter-file path
  4. Optionally invokes Claude (requires CLAUDE_CLI=true env, default off —
     by default Soumya runs the research himself when he opens a session)

Path note: this file lives in ~/Library/Application Support/tradepilot/
because launchd's TCC sandbox blocks reading scripts inside ~/Documents.
The script accesses ~/Documents at runtime, which is fine.
"""
from __future__ import annotations

